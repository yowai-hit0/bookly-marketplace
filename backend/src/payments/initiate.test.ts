/**
 * Starting a booking-fee payment (plan.md Task 16; spec §3.1 step 9;
 * data-model_v2.md §5.11, §6.2, §7.2), against real PostgreSQL with the provider
 * stubbed or pointed at a fake MTN.
 *
 * What is proven: the `payment` row -- `initiated`, `mtn_momo_direct`, its
 * `our_ref` generated by the database -- is committed and visible to another
 * connection BEFORE the provider hears a word, so a provider that throws, or MTN
 * unreachable at the very first HTTP call, still leaves the attempt on record;
 * the provider is handed exactly that `our_ref` and the booking's frozen fee.
 * Accepted, the row is `pending`; refused, unreachable or past the deadline, it
 * is `failed` with the reason, and the booking is untouched -- still
 * `pending_payment`, `hold_expires_at` identical to the millisecond. `amount_rwf`
 * is `booking_fee_rwf` exactly and never changes afterwards, not even when a
 * webhook settles it. A booking already paid, lapsed, expired, closed, free or
 * unknown starts nothing; an attempt still waiting inside the window blocks a
 * second prompt, and one outside it does not; and two taps at once make one
 * payment.
 *
 * The session fee (plan.md Task 18; spec §3.5 step 4, §6.15) takes the same
 * path, with the amount read from `bookingTotals()` as the attempt opens rather
 * than from a frozen column -- except where the photographer has already
 * requested a figure nobody has attempted, which is the figure the client pays.
 * It is owed only by a confirmed or completed booking, and a second session fee
 * after one has succeeded is a new row, which the booking-fee partial unique
 * index does not touch.
 */

