/**
 * Holds the backend to `openapi/openapi.yaml` (plan.md Phase 3): the spec is
 * valid, every route has an operation and the other way round, and real
 * responses match the schemas. Runs against local PostgreSQL like every other
 * route test.
 */

let prisma: PrismaClient;
let raw: pg.Client;
let world: PaymentWorld;

const NOW = new Date('2026-10-01T06:00:00Z');
const WEB_ORIGIN = 'https://bookly.example';

beforeAll(async () => {
  prisma = createPrismaClient(testDatabaseUrl());
  raw = connect();
  await raw.connect();
});

afterAll(async () => {
  await truncateAll(raw);
  await prisma.$disconnect();
  await raw.end();
});

beforeEach(async () => {
  await truncateAll(raw);
  world = await seedWorld(prisma);
});

function app(): Express {
  return createApp({
    corsOrigin: WEB_ORIGIN,
    auth: { prisma, sessionSecret: TEST_SECRET, webOrigin: WEB_ORIGIN, now: () => NOW },
    publicApi: { prisma, now: () => NOW, payments: { routing: routeTo(stubProvider()), secret: TEST_SECRET } },
    webhooks: { prisma, providers: { mtn_momo_direct: stubProvider() } },
  });
}

/** The world photographer's studio token. */
async function studioToken(): Promise<string> {
  const user = await prisma.appUser.findUniqueOrThrow({ where: { id: world.photographerUserId } });
  return (await issueToken(TEST_SECRET, 'studio', user, NOW)).token;
}

describe('the OpenAPI spec', () => {
  it('is a valid OpenAPI 3.1 document', async () => {
    const spec = await loadSpec();
    expect(Object.keys(spec.paths).length).toBeGreaterThan(0);
  });

  it('declares exactly the routes the code mounts', async () => {
    const spec = await loadSpec();
    const { routes, unmapped } = scanRoutes();

    // A router whose mount prefix nobody declared: the table fell behind.
    expect(unmapped, `routers missing from the mount table: ${unmapped.join(', ')}`).toEqual([]);

    const inCode = new Set(routes.map((route) => `${route.method.toUpperCase()} ${route.path}`));
    const inSpec = new Set(specOperations(spec).map((op) => `${op.method.toUpperCase()} ${op.path}`));

    const missingFromSpec = [...inCode].filter((route) => !inSpec.has(route)).sort();
    const missingFromCode = [...inSpec].filter((route) => !inCode.has(route)).sort();

    expect(missingFromSpec, `routes with no operation in the spec:\n${missingFromSpec.join('\n')}`).toEqual([]);
    expect(missingFromCode, `operations in the spec with no route:\n${missingFromCode.join('\n')}`).toEqual([]);
  });

  it('gives every operation an operationId', async () => {
    const spec = await loadSpec();
    const ids = specOperations(spec).map((op) => op.operationId);
    expect(new Set(ids).size, 'operationIds must be unique').toBe(ids.length);
    expect(ids.every((id) => /^[a-z][A-Za-z]+$/.test(id)), `odd operationIds: ${ids.join(', ')}`).toBe(true);
  });

  // The docs site vendors a bundled copy of this spec (docs-site/openapi.json)
  // so it can build and deploy without this folder present. That copy is
  // regenerated by `cd docs-site && npm run sync-spec`; this test fails if it
  // falls behind the source here, so the two cannot silently drift.
  it('matches the copy the docs site vendors', async () => {
    expect(
      existsSync(VENDORED_SPEC_PATH),
      `docs-site/openapi.json is missing. Generate it with:\n  cd docs-site && npm run sync-spec`,
    ).toBe(true);

    const [source, vendored] = await Promise.all([
      dereferenceSpec(SPEC_PATH),
      dereferenceSpec(VENDORED_SPEC_PATH),
    ]);
    // Both are fully dereferenced, so every operation is inlined identically.
    // They differ only in a bundling artifact: `redocly bundle` collects the
    // reusable schemas into a `components` section, whereas the source keeps
    // them in separate files that inline away. Drop that section (keeping
    // securitySchemes, which `security` references by name) and compare the rest.
    expect(
      normalizeSpec(vendored),
      'docs-site/openapi.json is out of date. Refresh it with:\n  cd docs-site && npm run sync-spec',
    ).toEqual(normalizeSpec(source));
  });
});

/** A spec without the bundler's inlined component library, so a dereferenced
 *  source and a bundled-then-dereferenced copy compare on their real content. */
function normalizeSpec(spec: unknown): unknown {
  const doc = spec as { components?: Record<string, unknown> };
  if (doc.components !== undefined) {
    const { schemas: _s, responses: _r, parameters: _p, ...rest } = doc.components;
    doc.components = rest;
  }
  return doc;
}

describe('responses match the spec', () => {
  it('public catalogue and availability', async () => {
    const server = app();
    await expectMatchesSpec(await request(server).get('/api/health'), 'getHealth', 200);
    await expectMatchesSpec(await request(server).get('/api/photographers'), 'listPhotographers', 200);
    await expectMatchesSpec(await request(server).get(`/api/photographers/${PHOTOGRAPHER_HANDLE}`), 'getPhotographer', 200);
    await expectMatchesSpec(
      await request(server).get(`/api/photographers/${PHOTOGRAPHER_HANDLE}/services`),
      'listPhotographerServices',
      200,
    );
    await expectMatchesSpec(
      await request(server).get(`/api/photographers/${PHOTOGRAPHER_HANDLE}/services/portraits`),
      'getPhotographerService',
      200,
    );
    await expectMatchesSpec(
      await request(server).post('/api/quote').send({ packageId: world.packageId, addonIds: [world.sharedAddonId] }),
      'createQuote',
      200,
    );
    await expectMatchesSpec(await request(server).get('/api/payment-methods'), 'getPaymentMethods', 200);
  });

  it('a booking created through the API', async () => {
    await seedWorkingHours(prisma);
    const server = app();
    const month = '2026-11';
    const availability = await request(server).get(`/api/availability?packageId=${world.packageId}&month=${month}`);
    await expectMatchesSpec(availability, 'getAvailability', 200);
    const startsAt = (availability.body as { days: { starts: string[] }[] }).days.flatMap((day) => day.starts)[0];
    expect(startsAt, 'seeded working hours should offer at least one slot').toBeDefined();

    const created = await request(server)
      .post('/api/bookings')
      .send({
        packageId: world.packageId,
        startsAt,
        fullName: 'Aline Uwase',
        email: 'aline@example.com',
        phone: '+250788123456',
        location: 'Kigali Heights',
        consent: true,
      });
    await expectMatchesSpec(created, 'createBooking', 201);
  });

  it('the Phase 3 payment-safety answers (marketplace-spec.md R3.4, T3.3)', async () => {
    const booking = await insertBooking(prisma, world);
    await prisma.photographer.update({ where: { id: world.photographerId }, data: { status: 'suspended', suspendedAt: NOW } });
    const token = checkoutToken(TEST_SECRET, booking.reference);
    await expectMatchesSpec(
      await request(app()).post(`/api/checkout/${booking.reference}/${token}/payments`).send({ method: 'momo_mtn', phone: '0788123456' }),
      'startCheckoutPayment',
      409,
    );

    const refusing = createApp({ webhooks: { prisma, providers: { mtn_momo_direct: stubProvider({ verifyWebhook: () => false }) } } });
    const ref = '3f0c6a52-8d1e-4b7a-9c35-0e4d2a61b7f8';
    await expectMatchesSpec(
      await request(refusing).post(`/api/webhooks/mtn-momo/${ref}/sig`).set('Content-Type', 'application/json').send('{}'),
      'mtnMomoWebhookPost',
      401,
    );
  });

  it("a client's own booking", async () => {
    const { token } = await insertBookingWithToken(prisma, world);
    await expectMatchesSpec(await request(app()).get(`/api/booking/${token}`), 'getClientBooking', 200);
  });

  it('a held booking at checkout', async () => {
    const server = app();
    await seedWorkingHours(prisma);
    const availability = await request(server).get(`/api/availability?packageId=${world.packageId}&month=2026-11`);
    const startsAt = (availability.body as { days: { starts: string[] }[] }).days.flatMap((day) => day.starts)[0]!;
    const created = await request(server)
      .post('/api/bookings')
      .send({ packageId: world.packageId, startsAt, fullName: 'A', email: 'a@example.com', phone: '+250788123456', location: 'Kigali', consent: true });
    const { reference } = (created.body as { booking: { reference: string } }).booking;
    const token = checkoutToken(TEST_SECRET, reference);
    await expectMatchesSpec(await request(server).get(`/api/checkout/${reference}/${token}`), 'getCheckout', 200);
  });

  it('studio auth', async () => {
    await prisma.appUser.update({ where: { id: world.photographerUserId }, data: { passwordHash: await hashPassword('a-good-enough-password') } });
    const server = app();
    const login = await request(server).post('/api/studio/auth/login').send({ email: ADMIN_EMAIL, password: 'a-good-enough-password' });
    await expectMatchesSpec(login, 'studioLogin', 200);

    const token = await studioToken();
    await expectMatchesSpec(await request(server).get('/api/studio/me').set('Authorization', `Bearer ${token}`), 'getStudioMe', 200);
  });

  it('signup, verification and the account area (Phase 2)', async () => {
    const server = app();
    const studio = { email: 'applicant@bookly.example', password: 'a-good-enough-password', displayName: 'Applicant', handle: 'applicant' };
    await expectMatchesSpec(await request(server).post('/api/studio/auth/signup').send(studio), 'studioSignup', 202);
    await expectMatchesSpec(await request(server).post('/api/studio/auth/signup').send({ ...studio, handle: 'kigali-lens' }), 'studioSignup', 409);
    await expectMatchesSpec(await request(server).post('/api/studio/auth/signup').send({ ...studio, password: 'short' }), 'studioSignup', 422);
    await expectMatchesSpec(await request(server).post('/api/studio/auth/verify/resend').send({ email: studio.email }), 'resendStudioVerification', 202);
    await expectMatchesSpec(await request(server).post('/api/platform/auth/verify').send({ token: 'x', password: 'y' }), 'verifyPlatformEmail', 400);

    const client = { email: 'new.client@bookly.example', password: 'a-good-enough-password', fullName: 'Aline' };
    await expectMatchesSpec(await request(server).post('/api/account/auth/signup').send(client), 'accountSignup', 202);
    const row = await prisma.outbox.findFirstOrThrow({ where: { template: 'account_verify_email', recipient: client.email } });
    const token = String((row.payload as Record<string, unknown>).token);
    const verified = await request(server).post('/api/account/auth/verify').send({ token, password: client.password });
    await expectMatchesSpec(verified, 'verifyAccountEmail', 200);
    const auth = { Authorization: `Bearer ${(verified.body as { token: string }).token}` };
    await expectMatchesSpec(await request(server).get('/api/account/me').set(auth), 'getAccountMe', 200);
    await expectMatchesSpec(await request(server).post('/api/account/auth/login').send(client), 'accountLogin', 200);
    await expectMatchesSpec(await request(server).get('/api/account/auth/providers'), 'getAccountAuthProviders', 200);
    await expectMatchesSpec(await request(server).post('/api/account/auth/google/start'), 'startGoogleSignIn', 404);
  });

  it('platform auth and photographers', async () => {
    const admin = await prisma.appUser.findFirstOrThrow({ where: { role: 'platform_admin' } });
    await prisma.appUser.update({ where: { id: admin.id }, data: { passwordHash: await hashPassword('a-good-enough-password') } });
    const server = app();
    const login = await request(server).post('/api/platform/auth/login').send({ email: PLATFORM_ADMIN_EMAIL, password: 'a-good-enough-password' });
    await expectMatchesSpec(login, 'platformLogin', 200);
    const auth = { Authorization: `Bearer ${(login.body as { token: string }).token}` };

    await expectMatchesSpec(await request(server).get('/api/platform/me').set(auth), 'getPlatformMe', 200);
    await expectMatchesSpec(await request(server).get('/api/platform/photographers?status=approved').set(auth), 'listPlatformPhotographers', 200);
    const path = `/api/platform/photographers/${world.photographerId}`;
    await expectMatchesSpec(await request(server).post(`${path}/suspend`).set(auth).send({ reason: 'Checking the spec' }), 'suspendPhotographer', 200);
    await expectMatchesSpec(await request(server).post(`${path}/approve`).set(auth), 'approvePhotographer', 409);
    await expectMatchesSpec(await request(server).post(`${path}/reactivate`).set(auth), 'reactivatePhotographer', 200);
    await expectMatchesSpec(await request(server).post(`${path}/approve`).set(auth), 'approvePhotographer', 200);
  });

  it('studio availability, settings and calendar', async () => {
    const server = app();
    const auth = { Authorization: `Bearer ${await studioToken()}` };
    await expectMatchesSpec(await request(server).get('/api/studio/working-hours').set(auth), 'listWorkingHours', 200);
    await expectMatchesSpec(await request(server).get('/api/studio/blocks').set(auth), 'listBlocks', 200);
    await expectMatchesSpec(await request(server).get('/api/studio/settings').set(auth), 'getSettings', 200);
    await expectMatchesSpec(
      await request(server).get('/api/studio/calendar?from=2026-10-01&to=2026-10-31').set(auth),
      'getCalendar',
      200,
    );
  });

  it('the subscription: the studio page, paying, polling, and the platform settings and list (Phase 5)', async () => {
    const server = app();
    const auth = { Authorization: `Bearer ${await studioToken()}` };
    await expectMatchesSpec(await request(server).get('/api/studio/subscription').set(auth), 'getStudioSubscription', 200);
    const started = await request(server).post('/api/studio/subscription/payments').set(auth).send({ planInterval: 'monthly', method: 'momo_mtn', phone: '0788123456' });
    await expectMatchesSpec(started, 'startSubscriptionPayment', 201);
    await expectMatchesSpec(
      await request(server).post('/api/studio/subscription/payments').set(auth).send({ planInterval: 'yearly', method: 'momo_mtn', phone: '0788123456' }),
      'startSubscriptionPayment',
      409,
    );
    await expectMatchesSpec(
      await request(server).post('/api/studio/subscription/payments').set(auth).send({ planInterval: 'monthly', method: 'momo_mtn', phone: '12' }),
      'startSubscriptionPayment',
      422,
    );
    const { ourRef } = (started.body as { payment: { ourRef: string } }).payment;
    await expectMatchesSpec(await request(server).get(`/api/studio/subscription/payments/${ourRef}`).set(auth), 'getStudioSubscriptionPayment', 200);
    await expectMatchesSpec(await request(server).get('/api/studio/subscription').set(auth), 'getStudioSubscription', 200);

    const admin = await prisma.appUser.findFirstOrThrow({ where: { role: 'platform_admin' } });
    const platform = { Authorization: `Bearer ${(await issueToken(TEST_SECRET, 'platform', admin, NOW)).token}` };
    await expectMatchesSpec(await request(server).get('/api/platform/settings').set(platform), 'getPlatformSettings', 200);
    await expectMatchesSpec(await request(server).patch('/api/platform/settings').set(platform).send({ subscriptionGraceDays: 5 }), 'updatePlatformSettings', 200);
    await expectMatchesSpec(await request(server).patch('/api/platform/settings').set(platform).send({ trialDays: 0 }), 'updatePlatformSettings', 422);
    await expectMatchesSpec(await request(server).get('/api/platform/subscriptions').set(platform), 'listPlatformSubscriptions', 200);
    await expectMatchesSpec(await request(server).get('/api/platform/subscriptions?status=trialing').set(platform), 'listPlatformSubscriptions', 200);
  });

  it('studio catalogue and bookings', async () => {
    const { booking } = await insertBookingWithToken(prisma, world);
    await insertPayment(prisma, booking.id, { kind: 'booking_fee', status: 'succeeded', amountRwf: 20_000 });
    const server = app();
    const auth = { Authorization: `Bearer ${await studioToken()}` };
    await expectMatchesSpec(await request(server).get('/api/studio/catalogue').set(auth), 'getCatalogue', 200);
    await expectMatchesSpec(await request(server).get('/api/studio/bookings').set(auth), 'listBookings', 200);
    await expectMatchesSpec(
      await request(server).get(`/api/studio/bookings/${booking.id}`).set(auth),
      'getBooking',
      200,
    );
  });
});

/** Mon–Fri 09:00–17:00, as the demo seed sets, so availability offers slots. */
async function seedWorkingHours(client: PrismaClient): Promise<void> {
  await client.workingHours.createMany({
    data: [1, 2, 3, 4, 5].map((weekday) => ({ photographerId: world.photographerId, weekday, opensMinute: 540, closesMinute: 1020, isOpen: true })),
  });
}
