import type { PrismaClient } from '@prisma/client';
import type { Express } from 'express';
import type pg from 'pg';
import request from 'supertest';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { createApp } from './app.js';
import { hashPassword } from './auth/password.js';
import { issueAdminToken } from './auth/token.js';
import { checkoutToken } from './payments/checkout-link.js';
import { createPrismaClient } from './db/client.js';
import { connect, testDatabaseUrl, truncateAll } from './test/database.js';
import {
  ADMIN_EMAIL,
  type PaymentWorld,
  TEST_SECRET,
  insertBookingWithToken,
  insertPayment,
  seedWorld,
  stubProvider,
} from './test/payment-fixtures.js';
import { existsSync } from 'node:fs';
import {
  SPEC_PATH,
  VENDORED_SPEC_PATH,
  dereferenceSpec,
  expectMatchesSpec,
  loadSpec,
  scanRoutes,
  specOperations,
} from './test/openapi.js';

/**
 * Holds the backend to `openapi/openapi.yaml` (plan.md Phase 3): the spec is
 * valid, every route has an operation and the other way round, and real
 * responses match the schemas. Runs against local PostgreSQL like every other
 * route test.
 */

let prisma: PrismaClient;
let raw: pg.Client;
let world: PaymentWorld;

const NOW = new Date('2026-10-01T06:00:00Z');
const WEB_ORIGIN = 'https://bookly.example';

beforeAll(async () => {
  prisma = createPrismaClient(testDatabaseUrl());
  raw = connect();
  await raw.connect();
});

afterAll(async () => {
  await truncateAll(raw);
  await prisma.$disconnect();
  await raw.end();
});

beforeEach(async () => {
  await truncateAll(raw);
  world = await seedWorld(prisma);
});

function app(): Express {
  return createApp({
    corsOrigin: WEB_ORIGIN,
    admin: { prisma, sessionSecret: TEST_SECRET, webOrigin: WEB_ORIGIN, now: () => NOW },
    publicApi: { prisma, now: () => NOW, payments: { provider: stubProvider(), secret: TEST_SECRET } },
    webhooks: { prisma, providers: { mtn_momo_direct: stubProvider() } },
  });
}

async function adminToken(): Promise<string> {
  const admin = await prisma.adminUser.findFirstOrThrow();
  return (await issueAdminToken(TEST_SECRET, admin, NOW)).token;
}

describe('the OpenAPI spec', () => {
  it('is a valid OpenAPI 3.1 document', async () => {
    const spec = await loadSpec();
    expect(Object.keys(spec.paths).length).toBeGreaterThan(0);
  });

  it('declares exactly the routes the code mounts', async () => {
    const spec = await loadSpec();
    const { routes, unmapped } = scanRoutes();

    // A router whose mount prefix nobody declared: the table fell behind.
    expect(unmapped, `routers missing from the mount table: ${unmapped.join(', ')}`).toEqual([]);

    const inCode = new Set(routes.map((route) => `${route.method.toUpperCase()} ${route.path}`));
    const inSpec = new Set(specOperations(spec).map((op) => `${op.method.toUpperCase()} ${op.path}`));

    const missingFromSpec = [...inCode].filter((route) => !inSpec.has(route)).sort();
    const missingFromCode = [...inSpec].filter((route) => !inCode.has(route)).sort();

    expect(missingFromSpec, `routes with no operation in the spec:\n${missingFromSpec.join('\n')}`).toEqual([]);
    expect(missingFromCode, `operations in the spec with no route:\n${missingFromCode.join('\n')}`).toEqual([]);
  });

  it('gives every operation an operationId', async () => {
    const spec = await loadSpec();
    const ids = specOperations(spec).map((op) => op.operationId);
    expect(new Set(ids).size, 'operationIds must be unique').toBe(ids.length);
    expect(ids.every((id) => /^[a-z][A-Za-z]+$/.test(id)), `odd operationIds: ${ids.join(', ')}`).toBe(true);
  });

  // The docs site vendors a bundled copy of this spec (docs-site/openapi.json)
  // so it can build and deploy without this folder present. That copy is
  // regenerated by `cd docs-site && npm run sync-spec`; this test fails if it
  // falls behind the source here, so the two cannot silently drift.
  it('matches the copy the docs site vendors', async () => {
    expect(
      existsSync(VENDORED_SPEC_PATH),
      `docs-site/openapi.json is missing. Generate it with:\n  cd docs-site && npm run sync-spec`,
    ).toBe(true);

    const [source, vendored] = await Promise.all([
      dereferenceSpec(SPEC_PATH),
      dereferenceSpec(VENDORED_SPEC_PATH),
    ]);
    // Both are fully dereferenced, so every operation is inlined identically.
    // They differ only in a bundling artifact: `redocly bundle` collects the
    // reusable schemas into a `components` section, whereas the source keeps
    // them in separate files that inline away. Drop that section (keeping
    // securitySchemes, which `security` references by name) and compare the rest.
    expect(
      normalizeSpec(vendored),
      'docs-site/openapi.json is out of date. Refresh it with:\n  cd docs-site && npm run sync-spec',
    ).toEqual(normalizeSpec(source));
  });
});

/** A spec without the bundler's inlined component library, so a dereferenced
 *  source and a bundled-then-dereferenced copy compare on their real content. */
function normalizeSpec(spec: unknown): unknown {
  const doc = spec as { components?: Record<string, unknown> };
  if (doc.components !== undefined) {
    const { schemas: _s, responses: _r, parameters: _p, ...rest } = doc.components;
    doc.components = rest;
  }
  return doc;
}

describe('responses match the spec', () => {
  it('public catalogue and availability', async () => {
    const server = app();
    await expectMatchesSpec(await request(server).get('/api/health'), 'getHealth', 200);
    await expectMatchesSpec(await request(server).get('/api/services'), 'listServices', 200);
    await expectMatchesSpec(await request(server).get('/api/services/portraits'), 'getService', 200);
    await expectMatchesSpec(
      await request(server).post('/api/quote').send({ packageId: world.packageId, addonIds: [world.sharedAddonId] }),
      'createQuote',
      200,
    );
    await expectMatchesSpec(await request(server).get('/api/payment-methods'), 'getPaymentMethods', 200);
  });

  it('a booking created through the API', async () => {
    await seedWorkingHours(prisma);
    const server = app();
    const month = '2026-11';
    const availability = await request(server).get(`/api/availability?packageId=${world.packageId}&month=${month}`);
    await expectMatchesSpec(availability, 'getAvailability', 200);
    const startsAt = (availability.body as { days: { starts: string[] }[] }).days.flatMap((day) => day.starts)[0];
    expect(startsAt, 'seeded working hours should offer at least one slot').toBeDefined();

    const created = await request(server)
      .post('/api/bookings')
      .send({
        packageId: world.packageId,
        startsAt,
        fullName: 'Aline Uwase',
        email: 'aline@example.com',
        phone: '+250788123456',
        location: 'Kigali Heights',
        consent: true,
      });
    await expectMatchesSpec(created, 'createBooking', 201);
  });

  it("a client's own booking", async () => {
    const { token } = await insertBookingWithToken(prisma, world);
    await expectMatchesSpec(await request(app()).get(`/api/booking/${token}`), 'getClientBooking', 200);
  });

  it('a held booking at checkout', async () => {
    const server = app();
    await seedWorkingHours(prisma);
    const availability = await request(server).get(`/api/availability?packageId=${world.packageId}&month=2026-11`);
    const startsAt = (availability.body as { days: { starts: string[] }[] }).days.flatMap((day) => day.starts)[0]!;
    const created = await request(server)
      .post('/api/bookings')
      .send({ packageId: world.packageId, startsAt, fullName: 'A', email: 'a@example.com', phone: '+250788123456', location: 'Kigali', consent: true });
    const { reference } = (created.body as { booking: { reference: string } }).booking;
    const token = checkoutToken(TEST_SECRET, reference);
    await expectMatchesSpec(await request(server).get(`/api/checkout/${reference}/${token}`), 'getCheckout', 200);
  });

  it('admin auth', async () => {
    await prisma.adminUser.updateMany({ data: { passwordHash: await hashPassword('a-good-enough-password') } });
    const server = app();
    const login = await request(server).post('/api/admin/auth/login').send({ email: ADMIN_EMAIL, password: 'a-good-enough-password' });
    await expectMatchesSpec(login, 'adminLogin', 200);

    const token = await adminToken();
    await expectMatchesSpec(await request(server).get('/api/admin/me').set('Authorization', `Bearer ${token}`), 'getAdminMe', 200);
  });

  it('admin availability, settings and calendar', async () => {
    const server = app();
    const auth = { Authorization: `Bearer ${await adminToken()}` };
    await expectMatchesSpec(await request(server).get('/api/admin/working-hours').set(auth), 'listWorkingHours', 200);
    await expectMatchesSpec(await request(server).get('/api/admin/blocks').set(auth), 'listBlocks', 200);
    await expectMatchesSpec(await request(server).get('/api/admin/settings').set(auth), 'getSettings', 200);
    await expectMatchesSpec(
      await request(server).get('/api/admin/calendar?from=2026-10-01&to=2026-10-31').set(auth),
      'getCalendar',
      200,
    );
  });

  it('admin catalogue and bookings', async () => {
    const { booking } = await insertBookingWithToken(prisma, world);
    await insertPayment(prisma, booking.id, { kind: 'booking_fee', status: 'succeeded', amountRwf: 20_000 });
    const server = app();
    const auth = { Authorization: `Bearer ${await adminToken()}` };
    await expectMatchesSpec(await request(server).get('/api/admin/catalogue').set(auth), 'getCatalogue', 200);
    await expectMatchesSpec(await request(server).get('/api/admin/bookings').set(auth), 'listBookings', 200);
    await expectMatchesSpec(
      await request(server).get(`/api/admin/bookings/${booking.id}`).set(auth),
      'getBooking',
      200,
    );
  });
});

/** Mon–Fri 09:00–17:00, as the real seed sets, so availability offers slots. */
async function seedWorkingHours(client: PrismaClient): Promise<void> {
  await client.workingHours.createMany({
    data: [1, 2, 3, 4, 5].map((weekday) => ({ weekday, opensMinute: 540, closesMinute: 1020, isOpen: true })),
  });
}
