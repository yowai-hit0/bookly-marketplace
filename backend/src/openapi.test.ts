describe('the OpenAPI spec', () => {
  it('is a valid OpenAPI 3.1 document', async () => {
    const spec = await loadSpec();
    expect(Object.keys(spec.paths).length).toBeGreaterThan(0);
  });

  it('declares exactly the routes the code mounts', async () => {
    const spec = await loadSpec();
    const { routes, unmapped } = scanRoutes();

    // A router whose mount prefix nobody declared: the table fell behind.
    expect(unmapped, `routers missing from the mount table: ${unmapped.join(', ')}`).toEqual([]);

    const inCode = new Set(routes.map((route) => `${route.method.toUpperCase()} ${route.path}`));
    const inSpec = new Set(specOperations(spec).map((op) => `${op.method.toUpperCase()} ${op.path}`));

    const missingFromSpec = [...inCode].filter((route) => !inSpec.has(route)).sort();
    const missingFromCode = [...inSpec].filter((route) => !inCode.has(route)).sort();

    expect(missingFromSpec, `routes with no operation in the spec:\n${missingFromSpec.join('\n')}`).toEqual([]);
    expect(missingFromCode, `operations in the spec with no route:\n${missingFromCode.join('\n')}`).toEqual([]);
  });

  it('gives every operation an operationId', async () => {
    const spec = await loadSpec();
    const ids = specOperations(spec).map((op) => op.operationId);
    expect(new Set(ids).size, 'operationIds must be unique').toBe(ids.length);
    expect(ids.every((id) => /^[a-z][A-Za-z]+$/.test(id)), `odd operationIds: ${ids.join(', ')}`).toBe(true);
  });

  // The docs site vendors a bundled copy of this spec (docs-site/openapi.json)
  // so it can build and deploy without this folder present. That copy is
  // regenerated by `cd docs-site && npm run sync-spec`; this test fails if it
  // falls behind the source here, so the two cannot silently drift.
  it('matches the copy the docs site vendors', async () => {
    expect(
      existsSync(VENDORED_SPEC_PATH),
      `docs-site/openapi.json is missing. Generate it with:\n  cd docs-site && npm run sync-spec`,
    ).toBe(true);

    const [source, vendored] = await Promise.all([
      dereferenceSpec(SPEC_PATH),
      dereferenceSpec(VENDORED_SPEC_PATH),
    ]);
    // Both are fully dereferenced, so every operation is inlined identically.
    // They differ only in a bundling artifact: `redocly bundle` collects the
    // reusable schemas into a `components` section, whereas the source keeps
    // them in separate files that inline away. Drop that section (keeping
    // securitySchemes, which `security` references by name) and compare the rest.
    expect(
      normalizeSpec(vendored),
      'docs-site/openapi.json is out of date. Refresh it with:\n  cd docs-site && npm run sync-spec',
    ).toEqual(normalizeSpec(source));
  });
});

/** A spec without the bundler's inlined component library, so a dereferenced
 *  source and a bundled-then-dereferenced copy compare on their real content. */
function normalizeSpec(spec: unknown): unknown {
  const doc = spec as { components?: Record<string, unknown> };
  if (doc.components !== undefined) {
    const { schemas: _s, responses: _r, parameters: _p, ...rest } = doc.components;
    doc.components = rest;
  }
  return doc;
}

